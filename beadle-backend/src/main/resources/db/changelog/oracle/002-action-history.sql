CREATE TABLE BEADLE_ACTION_HISTORY (
    ID                          NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    AT                          TIMESTAMP       NOT NULL,
    USER_NAME                   VARCHAR2(200)   NOT NULL,
    ACTION                      VARCHAR2(40)    NOT NULL,
    OBJECT_TYPE                 VARCHAR2(40),
    OBJECT_ID                   NUMBER(19),
    OBJECT_KEY                  VARCHAR2(200),
    DETAILS                     CLOB,
    OUTCOME                     VARCHAR2(10)    NOT NULL,
    MESSAGE                     VARCHAR2(4000),
    CORRELATION_ID              VARCHAR2(64),
    DURATION_MS                 NUMBER(19)      NOT NULL,
    CONSTRAINT PK_BEADLE_ACTION_HISTORY PRIMARY KEY (ID),
    CONSTRAINT CK_BEADLE_ACTION_HISTORY_ACTION CHECK (ACTION IN ('CHANGE_PREVIEWED', 'CHANGE_RAISED',
        'CHANGE_EDITED', 'CHANGE_TASKS_CREATED', 'SECURE_CODING_TICKET_CREATED', 'REMINDER_SENT', 'CHANGE_SYNCED',
        'PRODUCT_CREATED', 'PRODUCT_UPDATED', 'PRODUCT_DELETED', 'CHANGE_PROFILE_UPDATED', 'DEPARTMENT_CREATED',
        'DEPARTMENT_RENAMED', 'DEPARTMENT_DELETED', 'USER_SIGNED_IN', 'CALLBACK_PROTECH', 'CALLBACK_INTERNAL')),
    CONSTRAINT CK_BEADLE_ACTION_HISTORY_OBJECT_TYPE CHECK (OBJECT_TYPE IN ('CHANGE', 'PRODUCT', 'CHANGE_PROFILE',
        'DEPARTMENT', 'TICKET', 'USER')),
    CONSTRAINT CK_BEADLE_ACTION_HISTORY_OUTCOME CHECK (OUTCOME IN ('SUCCESS', 'FAILURE'))
);
CREATE INDEX IX_BEADLE_ACTION_HISTORY_AT ON BEADLE_ACTION_HISTORY (AT);
CREATE INDEX IX_BEADLE_ACTION_HISTORY_USER ON BEADLE_ACTION_HISTORY (USER_NAME);
CREATE INDEX IX_BEADLE_ACTION_HISTORY_ACTION ON BEADLE_ACTION_HISTORY (ACTION);
CREATE INDEX IX_BEADLE_ACTION_HISTORY_OBJECT_KEY ON BEADLE_ACTION_HISTORY (OBJECT_KEY);
--rollback DROP TABLE BEADLE_ACTION_HISTORY;
