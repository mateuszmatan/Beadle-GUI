-- Products and their services: every setting the DevSecOps library reads for a service, one changeset per table.
-- Written for Oracle 19c and later; the same changesets run on H2 in Oracle mode for local work and tests.

--changeset dso-portal:001-product dbms:oracle,h2
CREATE TABLE DSO_PRODUCT (
    ID                          NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    CODE                        VARCHAR2(50)    NOT NULL,
    NAME                        VARCHAR2(200)   NOT NULL,
    DESCRIPTION                 VARCHAR2(4000),
    OWNER_TEAM                  VARCHAR2(200),
    CONTACT_EMAIL               VARCHAR2(320),
    ASOC_KEY_ID                 VARCHAR2(200)   NOT NULL,
    ASOC_SECRET_CREDENTIALS_ID  VARCHAR2(200),
    CREATED_AT                  TIMESTAMP       NOT NULL,
    UPDATED_AT                  TIMESTAMP       NOT NULL,
    VERSION                     NUMBER(19)      DEFAULT 0 NOT NULL,
    CONSTRAINT PK_DSO_PRODUCT PRIMARY KEY (ID),
    CONSTRAINT UK_DSO_PRODUCT_CODE UNIQUE (CODE),
    CONSTRAINT UK_DSO_PRODUCT_NAME UNIQUE (NAME)
);
--rollback DROP TABLE DSO_PRODUCT;

--changeset dso-portal:001-service dbms:oracle,h2
CREATE TABLE DSO_SERVICE (
    ID                                  NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    PRODUCT_ID                          NUMBER(19)      NOT NULL,
    NAME                                VARCHAR2(100)   NOT NULL,
    DESCRIPTION                         VARCHAR2(2000),
    DISPLAY_ORDER                       NUMBER(10)      DEFAULT 0 NOT NULL,
    -- build
    BUILD_TOOL                          VARCHAR2(20)    NOT NULL,
    SOURCE_DIR                          VARCHAR2(500)   NOT NULL,
    JAVA_PATH                           VARCHAR2(500),
    BUILD_TOOL_AUTO_SETUP               NUMBER(1)       DEFAULT 0 NOT NULL,
    BUILD_PATH                          VARCHAR2(500),
    BUILD_TASKS                         VARCHAR2(1000),
    BUILD_FLAGS                         VARCHAR2(2000),
    BUILD_DIRECTORY                     VARCHAR2(500),
    BUILD_MAVEN_HOME                    VARCHAR2(500),
    BUILD_ENVIRONMENT                   VARCHAR2(4000),
    -- unit tests and coverage
    UNIT_TEST_TASKS                     VARCHAR2(1000),
    UNIT_TEST_FLAGS                     VARCHAR2(2000),
    UNIT_TEST_DIRECTORY                 VARCHAR2(500),
    UNIT_TEST_MAVEN_HOME                VARCHAR2(500),
    UNIT_TEST_ENVIRONMENT               VARCHAR2(4000),
    UNIT_TEST_RESULTS                   VARCHAR2(500),
    UNIT_TEST_ROOT_DIR                  VARCHAR2(500),
    UNIT_TEST_REPORT_DIR                VARCHAR2(500),
    UNIT_TEST_ALLOW_EMPTY               NUMBER(1)       DEFAULT 0 NOT NULL,
    COVERAGE_REPORT_PATH                VARCHAR2(500),
    -- smoke, regression and performance test runs (the jobs are in DSO_SERVICE_TEST_JOB)
    TESTS_MAX_PARALLEL                  NUMBER(10),
    SMOKE_MAX_PARALLEL                  NUMBER(10),
    REGRESSION_MAX_PARALLEL             NUMBER(10),
    PERFORMANCE_MAX_PARALLEL            NUMBER(10),
    -- deployment
    DEPLOY_TARGET                       VARCHAR2(20)    NOT NULL,
    APP_NAME                            VARCHAR2(200),
    ARTIFACT_NAME                       VARCHAR2(300),
    BASE_ARTIFACT_NAME                  VARCHAR2(300),
    DELIVERY_TASKS                      VARCHAR2(1000),
    DELIVERY_FLAGS                      VARCHAR2(2000),
    DELIVERY_DIRECTORY                  VARCHAR2(500),
    DELIVERY_MAVEN_HOME                 VARCHAR2(500),
    DELIVERY_ENVIRONMENT                VARCHAR2(4000),
    -- UrbanCode Deploy (the applications are in DSO_UCD_APPLICATION)
    UCD_SITE_NAME                       VARCHAR2(200),
    UCD_DEPLOY_PROCESS                  VARCHAR2(200),
    UCD_SKIP_WAIT                       NUMBER(1)       DEFAULT 0 NOT NULL,
    UCD_DEPLOY_WITH_SNAPSHOT            NUMBER(1)       DEFAULT 1 NOT NULL,
    UCD_UPDATE_SNAPSHOT_COMPONENTS      NUMBER(1)       DEFAULT 0 NOT NULL,
    UCD_INCLUDE_ONLY_DEPLOY_VERSIONS    NUMBER(1)       DEFAULT 1 NOT NULL,
    UCD_DEPLOY_ONLY_CHANGED             NUMBER(1)       DEFAULT 0 NOT NULL,
    UCD_DEPLOY_DESCRIPTION              VARCHAR2(1000),
    UCD_REQUEST_PROPERTIES              VARCHAR2(2000),
    -- HCL AppScan: SAST and DAST
    APPSCAN_APP_ID                      VARCHAR2(36)    NOT NULL,
    SAST_SCAN_NAME                      VARCHAR2(200),
    SAST_INCLUDED_DIRS                  VARCHAR2(2000),
    SAST_EXCLUDED_DIRS                  VARCHAR2(2000),
    APPSCAN_COMPILE                     NUMBER(1)       DEFAULT 1 NOT NULL,
    APPSCAN_SOURCE_CODE_ONLY            NUMBER(1)       DEFAULT 0 NOT NULL,
    APPSCAN_USE_CONFIG_FILE             NUMBER(1)       DEFAULT 0 NOT NULL,
    APPSCAN_INSECURE_TLS                NUMBER(1)       DEFAULT 0 NOT NULL,
    APPSCAN_CLIENT_PATH                 VARCHAR2(500),
    APPSCAN_COMPILE_TASKS               VARCHAR2(1000),
    APPSCAN_COMPILE_FLAGS               VARCHAR2(2000),
    APPSCAN_COMPILE_DIRECTORY           VARCHAR2(500),
    APPSCAN_COMPILE_MAVEN_HOME          VARCHAR2(500),
    APPSCAN_COMPILE_ENVIRONMENT         VARCHAR2(4000),
    DAST_ENABLED                        NUMBER(1)       DEFAULT 0 NOT NULL,
    DAST_SCAN_NAME                      VARCHAR2(200),
    DAST_TARGET_URL                     VARCHAR2(1000),
    DAST_PRESENCE_ID                    VARCHAR2(100),
    -- SonarQube
    SONAR_PROJECT_NAME                  VARCHAR2(200),
    SONAR_PROJECT_KEY                   VARCHAR2(400),
    SONAR_INSTALLATION_NAME             VARCHAR2(200),
    SONAR_CREDENTIALS_ID                VARCHAR2(200),
    SONAR_AUTH_TOKEN_CREDENTIALS_ID     VARCHAR2(200),
    SONAR_BADGE_TOKEN                   VARCHAR2(200),
    SONAR_ADD_BADGES                    NUMBER(1)       DEFAULT 0 NOT NULL,
    SONAR_FULL_BADGES                   NUMBER(1)       DEFAULT 0 NOT NULL,
    SONAR_TASKS                         VARCHAR2(1000),
    SONAR_FLAGS                         VARCHAR2(2000),
    SONAR_DIRECTORY                     VARCHAR2(500),
    SONAR_MAVEN_HOME                    VARCHAR2(500),
    SONAR_ENVIRONMENT                   VARCHAR2(4000),
    -- Nexus IQ and SCA
    NEXUS_IQ_APPLICATION                VARCHAR2(200),
    NEXUS_IQ_SCAN_PATTERNS              VARCHAR2(2000),
    NEXUS_IQ_STAGE                      VARCHAR2(50)    DEFAULT 'build' NOT NULL,
    NEXUS_IQ_FAIL_ON_NETWORK_ERROR      NUMBER(1)       DEFAULT 0 NOT NULL,
    SCA_SCAN_NAME                       VARCHAR2(200),
    -- Bitbucket
    REPOSITORY_URL                      VARCHAR2(1000),
    BITBUCKET_CREDENTIALS_ID            VARCHAR2(200),
    BITBUCKET_AUTH_TYPE                 VARCHAR2(20)    DEFAULT 'BASIC' NOT NULL,
    BITBUCKET_TYPE                      VARCHAR2(20),
    BITBUCKET_TARGET_BRANCH             VARCHAR2(200),
    BITBUCKET_CLONE_URL                 VARCHAR2(1000),
    BITBUCKET_REVIEWERS                 VARCHAR2(2000),
    -- GoldenFix; a null value inherits the global setting
    GOLDEN_FIX_ENABLED                  NUMBER(1)       DEFAULT 1 NOT NULL,
    GOLDEN_FIX_DIRECT_ONLY              NUMBER(1),
    GOLDEN_FIX_MIN_THREAT_LEVEL         NUMBER(10),
    GOLDEN_FIX_ECOSYSTEMS               VARCHAR2(200),
    GOLDEN_FIX_VERSION_TYPES            VARCHAR2(1000),
    GOLDEN_FIX_EXCLUDE_DIRS             VARCHAR2(2000),
    GOLDEN_FIX_VERIFY                   NUMBER(1),
    GOLDEN_FIX_VERIFY_ATTEMPTS          NUMBER(10),
    GOLDEN_FIX_VERIFY_TIMEOUT           NUMBER(10),
    GOLDEN_FIX_VERIFY_MAVEN             VARCHAR2(500),
    GOLDEN_FIX_VERIFY_GRADLE            VARCHAR2(500),
    GOLDEN_FIX_VERIFY_NPM               VARCHAR2(500),
    GOLDEN_FIX_VERIFY_PIP               VARCHAR2(500),
    GOLDEN_FIX_VERIFY_PUB               VARCHAR2(500),
    GOLDEN_FIX_AUTHOR_NAME              VARCHAR2(200),
    GOLDEN_FIX_AUTHOR_EMAIL             VARCHAR2(320),
    GOLDEN_FIX_TIME_ZONE                VARCHAR2(100),
    -- metrics in InfluxDB
    METRICS_ENABLED                     NUMBER(1)       DEFAULT 1 NOT NULL,
    INFLUX_PROJECT                      VARCHAR2(200)   NOT NULL,
    INFLUX_ENV                          VARCHAR2(50)    DEFAULT 'test' NOT NULL,
    -- Flutter
    FLUTTER_PLATFORM                    VARCHAR2(20),
    FLUTTER_MODULES                     VARCHAR2(1000),
    FLUTTER_TEST_MODULES                VARCHAR2(1000),
    FLUTTER_TEST_SUBMODULES             VARCHAR2(1000),
    FLUTTER_TEST_SUBPLUGINS             VARCHAR2(1000),
    FLUTTER_SIGNING_CREDENTIALS_ID      VARCHAR2(200),
    FLUTTER_PROD_LICENSE_CREDENTIALS_ID VARCHAR2(200),
    FLUTTER_TEST_LICENSE_CREDENTIALS_ID VARCHAR2(200),
    FLUTTER_DELIVERY_GROUP              VARCHAR2(200),
    FLUTTER_DELIVERY_ARTIFACT           VARCHAR2(200),
    FLUTTER_DELIVERY_PLUGIN             VARCHAR2(300),
    FLUTTER_SONAR_SOURCES               VARCHAR2(500),
    FLUTTER_SONAR_TESTS                 VARCHAR2(500),
    FLUTTER_SONAR_PLUGIN                NUMBER(1)       DEFAULT 0 NOT NULL,
    FLUTTER_DART_ANALYZE_COMMAND        VARCHAR2(500),
    FLUTTER_SONAR_SCANNER_VERSION       VARCHAR2(50),
    CREATED_AT                          TIMESTAMP       NOT NULL,
    UPDATED_AT                          TIMESTAMP       NOT NULL,
    VERSION                             NUMBER(19)      DEFAULT 0 NOT NULL,
    CONSTRAINT PK_DSO_SERVICE PRIMARY KEY (ID),
    CONSTRAINT FK_DSO_SERVICE_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES DSO_PRODUCT (ID) ON DELETE CASCADE,
    CONSTRAINT UK_DSO_SERVICE_NAME UNIQUE (PRODUCT_ID, NAME),
    CONSTRAINT UK_DSO_SERVICE_INFLUX UNIQUE (INFLUX_PROJECT, INFLUX_ENV),
    CONSTRAINT UK_DSO_SERVICE_SONAR_KEY UNIQUE (SONAR_PROJECT_KEY),
    CONSTRAINT CK_DSO_SERVICE_BUILD_TOOL CHECK (BUILD_TOOL IN ('GRADLE', 'MAVEN', 'FLUTTER')),
    CONSTRAINT CK_DSO_SERVICE_DEPLOY_TARGET CHECK (DEPLOY_TARGET IN ('VM', 'OPENSHIFT')),
    CONSTRAINT CK_DSO_SERVICE_BB_AUTH CHECK (BITBUCKET_AUTH_TYPE IN ('BASIC', 'BEARER')),
    CONSTRAINT CK_DSO_SERVICE_BB_TYPE CHECK (BITBUCKET_TYPE IN ('SERVER', 'CLOUD')),
    CONSTRAINT CK_DSO_SERVICE_FLUTTER CHECK (
        FLUTTER_PLATFORM IN ('APK', 'APPBUNDLE', 'IOS', 'MACOS', 'LINUX', 'WINDOWS', 'WEB')),
    CONSTRAINT CK_DSO_SERVICE_FLAGS CHECK (BUILD_TOOL_AUTO_SETUP IN (0, 1) AND UNIT_TEST_ALLOW_EMPTY IN (0, 1)
        AND UCD_SKIP_WAIT IN (0, 1) AND UCD_DEPLOY_WITH_SNAPSHOT IN (0, 1) AND UCD_UPDATE_SNAPSHOT_COMPONENTS IN (0, 1)
        AND UCD_INCLUDE_ONLY_DEPLOY_VERSIONS IN (0, 1) AND UCD_DEPLOY_ONLY_CHANGED IN (0, 1)
        AND APPSCAN_COMPILE IN (0, 1) AND APPSCAN_SOURCE_CODE_ONLY IN (0, 1) AND APPSCAN_USE_CONFIG_FILE IN (0, 1)
        AND APPSCAN_INSECURE_TLS IN (0, 1) AND DAST_ENABLED IN (0, 1) AND SONAR_ADD_BADGES IN (0, 1)
        AND SONAR_FULL_BADGES IN (0, 1) AND NEXUS_IQ_FAIL_ON_NETWORK_ERROR IN (0, 1) AND GOLDEN_FIX_ENABLED IN (0, 1)
        AND GOLDEN_FIX_DIRECT_ONLY IN (0, 1) AND GOLDEN_FIX_VERIFY IN (0, 1) AND METRICS_ENABLED IN (0, 1)
        AND FLUTTER_SONAR_PLUGIN IN (0, 1)),
    CONSTRAINT CK_DSO_SERVICE_DAST CHECK (DAST_ENABLED = 0 OR DAST_TARGET_URL IS NOT NULL)
